const DICTS: Record<Language, Dict> = { en: EN, id: ID, zh: ZH, es: {} }

// Build a translator for a language (English fallback for any missing key).
export function dtFor(language: Language) {
  const d = DICTS[language] || EN
  return (key: string) => d[key] || EN[key] || key
}

// Hook: a `dt(key)` bound to the app's current language (reacts to changes).
export function useDispatchT() {
  const { language } = useI18n()
  return dtFor(language)
}
