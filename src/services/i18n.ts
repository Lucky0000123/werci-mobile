// Get current language from localStorage
export function getCurrentLanguage(): Language {
  const stored = localStorage.getItem('wbnkis_language')
  return (stored === 'en' || stored === 'es' || stored === 'id' || stored === 'zh') ? stored : 'id' // Default to Bahasa Indonesia
}

// Set language and persist to localStorage
export function setLanguage(lang: Language): void {
  localStorage.setItem('wbnkis_language', lang)
  // Dispatch custom event to notify components
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: lang }))
}

// Toggle between languages (cycles through: id -> en -> zh -> id). Spanish is
// retained in the type for back-compat but removed from the user-facing cycle.
export function toggleLanguage(): Language {
  const current = getCurrentLanguage()
  let newLang: Language
  if (current === 'id') {
    newLang = 'en'
  } else if (current === 'en') {
    newLang = 'zh'
  } else {
    newLang = 'id'
  }
  setLanguage(newLang)
  return newLang
}

// Get translated text for a key
export function t(key: keyof typeof translations.en): string {
  const lang = getCurrentLanguage()
  return translations[lang][key] || translations.en[key] || key
}

// Hook for components to react to language changes
export function useLanguage(): { lang: Language; setLang: (lang: Language) => void; t: (key: keyof typeof translations.en) => string } {
  const [lang, setLangState] = useState<Language>(getCurrentLanguage())

  useEffect(() => {
    const handleChange = (e: Event) => {
      const customEvent = e as CustomEvent<Language>
      setLangState(customEvent.detail)
    }
    window.addEventListener('languageChanged', handleChange)
    return () => window.removeEventListener('languageChanged', handleChange)
  }, [])

  const setLang = (newLang: Language) => {
    setLanguage(newLang)
    setLangState(newLang)
  }

  return { lang, setLang, t }
}

